-- DATE - Date

-- TIME - Time

-- TIMESTAMP - Date + Time 

-- TIMESTAMPTZ - Date + Time + timezone handling



-- CURRENT DATE
SELECT CURRENT_DATE;


-- CURRENT TIME
SELECT CURRENT_TIME;


-- CURRENT DATE + TIME
SELECT CURRENT_TIMESTAMP;

SELECT NOW();



-- EXTRACTING Year,Month,Day,TIMESTAMP
SELECT DATE '2026-08-19'

SELECT EXTRACT(YEAR FROM DATE '2026-08-19');

SELECT EXTRACT(MONTH FROM DATE '2026-08-19');

SELECT EXTRACT(DAY FROM DATE '2026-08-19');

-- TIMESTAMP
SELECT EXTRACT(HOUR FROM TIMESTAMP '2026-08-19 14:30:45');


